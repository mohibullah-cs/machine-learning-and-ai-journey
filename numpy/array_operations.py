import numpy as np

a = np.array([10, 20, 30])
b = np.array([2, 4, 6])

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)

print("Square:", a ** 2)
print("Greater than 15:", a > 15)

print("Total:", np.sum(a))
print("Maximum:", np.max(a))
print("Minimum:", np.min(a))
